/** Start of a Combat Round: the Round Limiter counts down; the Fusion goes back to its rolled Initiative. */
export async function fusionStartRound(combat) {
  const fusions = combat.combatants.map(cb => cb.actor).filter(a => (a?.type === "fusion") && a.system.fusion.active);
  for ( const fusion of new Set(fusions) ) {
    const init = fusion.getFlag(FLAG, "fusionInitiative");
    if ( init && (init.combat === combat.id) && (combat.round > init.round) ) {
      const cb = combat.combatants.find(c => c.actorId === fusion.id);
      if ( cb ) await cb.update({ initiative: init.initiative });
      await fusion.unsetFlag(FLAG, "fusionInitiative");
    }
    const method = FUSION_METHODS[fusion.system.fusion.method];
    if ( method?.type !== "temporary" ) continue;
    const left = Math.max(0, (fusion.system.fusion.roundsLeft ?? 0) - 1);
    await fusion.update({ "system.fusion.roundsLeft": left }, { dbuFusionSync: true });
    if ( left <= 0 ) await defuse(fusion, { reason: "time" });
    else await postInfoCard({ actor: fusion, title: fusion.name, lines: [L("DBU.Fusion.RoundsLeft", { n: left })], img: fusion.img });
  }
}

/** A Fused Character that just came back skips its turn this Combat Round. */
export async function fusionSkipTurn(combat, combatant) {
  const actor = combatant.actor;
  const skip = actor?.getFlag(FLAG, "fusionSkip");
  if ( !skip || (skip.combat !== combat.id) || (skip.round !== combat.round) ) return false;
  await actor.unsetFlag(FLAG, "fusionSkip");
  await postInfoCard({ actor, title: actor.name, lines: [L("DBU.Fusion.SkipTurn", { name: actor.name })] });
  setTimeout(() => combat.nextTurn(), 300);
  return true;
}

/**
 * Round Limiter: the first time in a Combat Encounter the Fusion enters a Transformation with a Tier of Power
 * Requirement of 4+, its remaining Combat Rounds drop by half of that Requirement (rounded up).
 */
export async function fusionTransformed(fusion, item) {
  const fs = fusion.system.fusion;
  if ( !fs?.active || fs.topReduced || (FUSION_METHODS[fs.method]?.type !== "temporary") ) return null;
  const req = item.system.topReq ?? 0;
  if ( (req < 4) || !game.combat?.started ) return null;
  const cut = Math.ceil(req / 2);
  const left = Math.max(0, fs.roundsLeft - cut);
  await fusion.update({ "system.fusion.roundsLeft": left, "system.fusion.topReduced": true }, { dbuFusionSync: true });
  return L("DBU.Fusion.TopCut", { name: item.name, n: cut, left });
}
