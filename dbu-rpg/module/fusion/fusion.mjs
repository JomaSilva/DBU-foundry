/**
 * Metamoran Fusion Dance: both Fused Characters make a Performance Skill Check (Master; one category higher when
 * their Size differs). Both succeed: Metamorese Fusion. One fails: 1d4 (1 = Frail, 2~4 = Plump). Both fail: nothing.
 */
export async function rollFusionDance(fusion) {
  const comps = getComponents(fusion);
  if ( comps.length !== 2 ) return ui.notifications.warn(L("DBU.Fusion.NeedTwo"));
  const sameSize = comps[0].system.details.size === comps[1].system.details.size;
  const difficulty = sameSize ? "master" : "grandmaster";
  const tn = DBU.difficulties[difficulty].tn;
  const results = [];
  for ( const c of comps ) {
    const r = await c.rollSkill("performance", { difficulty });
    results.push({ name: c.name, total: r?.total ?? 0, success: (r?.total ?? 0) >= tn });
  }
  const passed = results.filter(r => r.success).length;
  const lines = results.map(r => L(r.success ? "DBU.Fusion.Dance.Pass" : "DBU.Fusion.Dance.Fail", { name: r.name, total: r.total, tn }));
  let dance = null;
  if ( passed === 2 ) dance = "success";
  else if ( passed === 1 ) {
    const roll = await new Roll("1d4").evaluate();
    await roll.toMessage({ speaker: ChatMessage.getSpeaker({ actor: fusion }), flavor: L("DBU.Fusion.Dance.D4") });
    dance = roll.total === 1 ? "frail" : "plump";
  }
  if ( dance ) {
    await fusion.update({ "system.fusion.dance": dance, "system.fusion.method": "metamorese" });
    lines.push(L(`DBU.Fusion.Dance.${dance}`));
  }
  else lines.push(L("DBU.Fusion.Dance.Nothing"));
  await postInfoCard({ actor: fusion, title: L("DBU.Fusion.Dance.Title"), lines, img: fusion.img });
  return dance;
}

/**
 * Fused Technique: an Ultimate Signature Technique made from two Signature Techniques of different Fused Characters.
 * The base loses its Disadvantages, takes the other's Advantages, gains a Super Profile and costs 4(T) Ki Points less.
 */
export async function createFusedTechnique(fusion) {
  const comps = getComponents(fusion);
  const lists = comps.map(c => ({ comp: c, sigs: c.items.filter(i => i.type === "signature") }));
  const all = lists.flatMap(l => l.sigs.map(s => ({ s, comp: l.comp })));
  if ( lists.filter(l => l.sigs.length).length < 2 ) return ui.notifications.warn(L("DBU.Fusion.Tech.NeedTwo"));
  const esc = foundry.utils.escapeHTML;
  const option = ({ s, comp }, i) => `<option value="${i}">${esc(s.name)} — ${esc(comp.name)} (${esc(DBU.profiles[s.system.profile]?.label ?? s.system.profile)})</option>`;
  const options = all.map(option).join("");
  const supers = [
    `<option value="annihilation">Complete Annihilation</option>`,
    `<option value="super">${L("DBU.Fusion.Tech.SuperOfBase")}</option>`,
    `<option value="multiProfile">Multi-Profile</option>`
  ].join("");
  const content = `<div class="dbu-fusion-tech">
    <p>${L("DBU.Fusion.Tech.Hint")}</p>
    <label>${L("DBU.Fusion.Tech.Base")} <select name="base">${options}</select></label>
    <label>${L("DBU.Fusion.Tech.Other")} <select name="other">${all.map((x, i) => option(x, i)).join("")}</select></label>
    <label>${L("DBU.Fusion.Tech.Super")} <select name="super">${supers}</select></label>
    <label>${L("DBU.Fusion.Tech.Name")} <input type="text" name="name" value=""></label>
  </div>`;
  const pick = await DialogV2.prompt({
    window: { title: L("DBU.Fusion.Tech.Title") }, content, rejectClose: false,
    render: (event, dialog) => {
      const other = dialog.element.querySelector('select[name="other"]');
      if ( other && all.length > 1 ) other.value = String(all.findIndex(x => x.comp !== all[0].comp));
    },
    ok: { label: L("DBU.Fusion.Tech.Create"), callback: (event, button) => ({
      base: Number(button.form.elements.base.value), other: Number(button.form.elements.other.value),
      super: button.form.elements.super.value, name: button.form.elements.name.value.trim()
    }) }
  });
  if ( !pick ) return null;
  const base = all[pick.base], other = all[pick.other];
  if ( !base || !other || (base.comp === other.comp) ) return ui.notifications.warn(L("DBU.Fusion.Tech.Different"));
  // Qualifying Advantages of the other technique are added onto the base (ranks add up to the Advantage's maximum)
  const advantages = foundry.utils.deepClone(base.s.system._source.advantages);
  const maxRank = key => SIGNATURE_OPTIONS[key]?.costs?.length ?? 1;
  for ( const a of other.s.system._source.advantages ) {
    const same = advantages.find(x => x.key === a.key);
    if ( same ) same.rank = Math.min(maxRank(a.key), same.rank + a.rank);
    else advantages.push(foundry.utils.deepClone(a));
  }
  let superProfile = pick.super;
  let multiProfile = "";
  if ( superProfile === "super" ) {
    const map = { beam: "superBeam", combination: "superCombination", launching: "superLaunch" };
    superProfile = map[base.s.system.profile] ?? "annihilation";
  }
  if ( superProfile === "multiProfile" ) multiProfile = other.s.system.profile;
  const sharedHeritage = activeModifiers(fusion, analyzeFusion(fusion)).includes("sharedHeritage");
  const data = base.s.toObject();
  delete data._id;
  data.name = pick.name || `${base.s.name} + ${other.s.name}`;
  foundry.utils.mergeObject(data, {
    system: {
      level: "ultimate", disadvantages: [], advantages, superProfile, multiProfile,
      fused: true, fusedWoundT: sharedHeritage ? 2 * comps.length : 0, granted: true, free: false, usedThisEncounter: false
    },
    flags: { [FLAG]: { fusion: { keep: true, fusedTechnique: true } } }
  });
  const previous = fusion.items.filter(i => i.flags?.[FLAG]?.fusion?.fusedTechnique).map(i => i.id);
  if ( previous.length ) await fusion.deleteEmbeddedDocuments("Item", previous);
  const [item] = await fusion.createEmbeddedDocuments("Item", [data]);
  ui.notifications.info(L("DBU.Fusion.Tech.Created", { name: item.name }));
  return item;
}

