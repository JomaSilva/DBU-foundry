const timers = new Map();

/** Synchronize a Fusion a moment after its Fused Characters (or its own choices) change. */
export function scheduleSync(fusion) {
  if ( !fusion || fusion.system.fusion?.active || !fusion.system.fusion?.autoSync ) return;
  clearTimeout(timers.get(fusion.id));
  timers.set(fusion.id, setTimeout(() => {
    timers.delete(fusion.id);
    syncFusion(fusion, { silent: true }).catch(err => console.error("DBU | fusion sync", err));
  }, 700));
}

/**
 * Build the Fusion from its Fused Characters: steps 2–4, 6–8 and 10 of Character Combination,
 * the Method Traits, the Fusion Modifiers and the Fusion Awakening Limit. Choices already made are kept.
 */
export async function syncFusion(fusion, { silent = false } = {}) {
  if ( !fusion?.isOwner || (fusion.type !== "fusion") ) return null;
  const fs = fusion.system.fusion;
  if ( fs.active ) {
    if ( !silent ) ui.notifications.warn(L("DBU.Fusion.SyncActive"));
    return null;
  }
  const A = analyzeFusion(fusion);
  if ( A.comps.length < 2 ) {
    if ( !silent ) ui.notifications.warn(L("DBU.Fusion.NeedTwo"));
    return null;
  }
  const method = A.method;
  const modKeys = activeModifiers(fusion, A);
  const plump = fs.dance !== "success";

  // Choices kept from the previous synchronization (the first one uses the defaults)
  const traitPicks = fs.picked ? fs.traits.filter(n => A.traits.some(t => t.key === n)) : defaultTraitPicks(A);
  const awakPicks = fs.picked ? fs.awakenings.filter(n => A.awakenings.some(t => t.key === n)) : defaultAwakeningPicks(A);
  const fusedForms = modKeys.includes("fusedTransformation") ? A.sharedForms.map(f => f.name) : [];
  const pl = fusionPowerLevel(fusion, A);
  const bT = Math.min(7, Math.floor(Math.min(pl, 30) / 5) + 1);

  const create = [];
  const seen = new Set();
  const once = (type, name) => {
    const k = `${type}|${nameKey(name)}`;
    if ( seen.has(k) ) return false;
    seen.add(k);
    return true;
  };

  // Races, the chosen Racial Traits
  for ( const r of A.races ) if ( once("race", r.name) ) create.push(copyItem(r, r.parent));
  for ( const t of A.traits ) if ( traitPicks.includes(t.key) && once("racialTrait", t.item.name) ) create.push(copyItem(t.item, t.comp));

  // Talents, Transformations (with Masteries), Signature Techniques, Unique Abilities, Maneuvers and Items
  const transformations = new Map();
  for ( const c of A.comps ) {
    for ( const item of c.items ) {
      switch ( item.type ) {
        case "talent": case "maneuver":
          if ( once(item.type, item.name) ) create.push(copyItem(item, c));
          break;
        case "uniqueAbility":
          if ( once(item.type, item.name) ) create.push(copyItem(item, c, { system: { granted: true } }));
          break;
        case "signature":
          // Already paid for by the Fused Characters: they do not use the Fusion's Technique Points
          if ( once(item.type, item.name) ) create.push(copyItem(item, c, { system: { granted: true, free: false, usedThisEncounter: false } }));
          break;
        case "transformation": {
          const s = item.system;
          if ( (s.transType === "awakening") && !awakPicks.includes(item.name) ) break;
          const prev = transformations.get(nameKey(item.name));
          // The same Transformation from two Fused Characters: keep the higher Mastery
          if ( prev && (prev.item.system.mastery >= s.mastery) ) {
            prev.everEntered ||= s.everEntered;
            break;
          }
          transformations.set(nameKey(item.name), { item, comp: c, everEntered: (prev?.everEntered ?? false) || s.everEntered });
          break;
        }
        case "weapon": case "item":
          create.push(copyItem(item, c));
          break;
        case "apparel":
          if ( method.apparel?.startsWith("metamoran") || (method.forgo && fs.forgoApparel) ) break;
          create.push(copyItem(item, c));
          break;
        default: break;
      }
    }
  }
  for ( const { item, comp, everEntered } of transformations.values() ) {
    const extra = { system: { active: false, viaManeuver: false, newLevel: false, legendRealized: false, everEntered } };
    // Fused Transformation: a Form all the Fused Characters have gets a bigger Attribute Modifier Bonus
    if ( fusedForms.some(n => nameKey(n) === nameKey(item.name)) ) {
      const amount = item.system.subtype === "legendary" ? "2(T)" : "1(T)";
      extra.system.modifiers = [...(item.system._source?.modifiers ?? item.system.modifiers ?? []),
        ...PHYSICAL.map(a => mod(`mod.${a}`, amount, "Fused Transformation (4)"))];
    }
    create.push(copyItem(item, comp, extra));
  }
  // Fused Transformation: the higher Stages of the Fused Form's line the base ToP allows
  if ( fusedForms.length ) {
    const pack = game.packs.get("dbu-rpg.transformations");
    const index = pack ? await pack.getIndex({ fields: ["system.line", "system.stage", "system.topReq", "system.transType"] }) : [];
    // Only the Stages above the highest one the Fusion already has in that line (not the variants of a Stage it has)
    const lines = new Map();
    for ( const { item } of transformations.values() ) {
      const s = item.system;
      if ( s.line && (s.transType === "form") ) lines.set(s.line, Math.max(lines.get(s.line) ?? 0, s.stage ?? 0));
    }
    for ( const name of fusedForms ) {
      const form = A.sharedForms.find(f => f.name === name);
      const line = form?.system.line;
      if ( !line ) continue;
      for ( const e of index ) {
        const s = e.system ?? {};
        if ( (s.line !== line) || !(s.stage > (lines.get(line) ?? form.system.stage)) || ((s.topReq ?? 99) > bT) ) continue;
        if ( transformations.has(nameKey(e.name)) || !once("stage", e.name) ) continue;
        const doc = (await pack.getDocument(e._id)).toObject();
        delete doc._id;
        doc.flags = { [FLAG]: { fusion: { generated: "stage" } } };
        create.push(doc);
      }
    }
  }

  // Method Trait, Fusion Modifiers, Metamoran Clothing
  const methodMods = [...(method.modifiers ?? [])];
  if ( method.forgo && fs.forgoApparel ) {
    methodMods.push(mod("combat", "2(bT)", `${method.trait} (1)`), mod("dr", "2(bT)", `${method.trait} (1)`));
  }
  create.push(generatedTrait("method", method.trait, L(`DBU.Fusion.MethodSummary.${fs.method}`), { modifiers: methodMods }));
  for ( const k of modKeys ) {
    let summary = L(`DBU.Fusion.ModSummary.${k}`);
    if ( k === "balanced" ) summary += ` (${balancedPicks(fs, A).map(a => DBU.attributeAbbr[a]).join(", ")})`;
    create.push(generatedTrait(`modifier:${k}`, FUSION_MODIFIERS[k].label, summary, modifierEffects(k, fusion, A)));
  }
  if ( method.apparel?.startsWith("metamoran") ) create.push(metamoranClothing(method.apparel === "metamoranDivine"));
  // The Fused Characters' own custom bonuses (Progression tab), each one once
  const seenCustom = new Set();
  const customMods = [];
  const customTrigs = [];
  for ( const c of A.comps ) {
    for ( const m of c.system._source.customModifiers ?? [] ) {
      const k = `${m.target}|${m.value}|${m.condition}`;
      if ( !m.target || seenCustom.has(k) ) continue;
      seenCustom.add(k);
      customMods.push({ ...m, label: m.label || c.name });
    }
    for ( const t of c.system._source.customTriggers ?? [] ) {
      const k = `${t.event}|${t.effect}|${t.value}|${t.resource}|${t.condition}`;
      if ( seenCustom.has(k) ) continue;
      seenCustom.add(k);
      customTrigs.push({ ...t, label: t.label || c.name });
    }
  }
  if ( customMods.length || customTrigs.length ) {
    create.push(generatedTrait("custom", L("DBU.Fusion.CustomName"), L("DBU.Fusion.CustomSummary", { names: A.comps.map(c => c.name).join(", ") }),
      { modifiers: customMods, triggers: customTrigs }));
  }

  // Replace the previously synchronized items (the Fused Technique and items made for the Fusion stay)
  const old = fusion.items.filter(isSyncedItem).map(i => i.id);
  if ( old.length ) await fusion.deleteEmbeddedDocuments("Item", old, { dbuFusionSync: true });
  await fusion.createEmbeddedDocuments("Item", create, { dbuFusionSync: true });

  // Size (between the smallest and largest base Size; Merge Fusion may grow), Alignment, Karma, Skills, Scores
  const sizes = DBU.SIZE_ORDER;
  let sizeIdx = sizes.indexOf(fs.size);
  if ( (sizeIdx < A.size.min) || (sizeIdx > A.size.max) ) sizeIdx = A.size.leader;
  if ( method.sizeUp && fs.sizeUp ) sizeIdx = Math.min(sizes.length - 1, A.size.max + (A.comps.length >= 3 ? 2 : 1));
  const align = Math.clamp(fusion.system.zsoul.alignment, A.alignment.min, A.alignment.max);
  const updates = {
    "prototypeToken.actorLink": true,
    "system.pl": pl,
    "system.fusion.scores": A.scores,
    "system.fusion.traits": traitPicks,
    "system.fusion.awakenings": awakPicks,
    "system.fusion.picked": true,
    "system.fusion.fusedForms": fusedForms,
    "system.fusion.tp": fusionTechniquePoints(fusion, A),
    "system.fusion.syncedAt": Date.now(),
    "system.details.size": sizes[sizeIdx] ?? "medium",
    "system.zsoul.alignment": align,
    "system.karma.value": A.karma
  };
  // Age (Optional Rule, table decision): the Fusion's body is always at its Peak; its mind is the oldest of them
  const peak = AGE_CATEGORIES.indexOf("peak");
  const mental = A.comps.map(c => {
    const i = AGE_CATEGORIES.indexOf(c.system._source.optional?.mentalAge ?? "peak");
    return (i < 0) ? peak : i;
  });
  updates["system.optional.physicalAge"] = "peak";
  updates["system.optional.mentalAge"] = AGE_CATEGORIES[Math.max(...mental)] ?? "peak";
  for ( const a of Object.keys(fusion.system._source.attributes) ) updates[`system.attributes.${a}.points`] = 0;
  for ( const [k, v] of Object.entries(A.skills) ) {
    updates[`system.skills.${k}.ranks`] = v;
    updates[`system.skills.${k}.racial`] = 0;
    updates[`system.skills.${k}.bonusRanks`] = 0;
  }
  await fusion.update(updates, { dbuFusionSync: true, dbuAllowOver: true });
  await fusion.update({
    "system.life.value": fusion.system.life.max, "system.ki.value": fusion.system.ki.max,
    "system.capacity.value": fusion.system.capacity.max
  }, { dbuFusionSync: true });
  if ( !silent ) ui.notifications.info(L("DBU.Fusion.Synced", { name: fusion.name }));
  if ( plump && !silent ) ui.notifications.warn(L(`DBU.Fusion.Dance.${fs.dance}`));
  return fusion;
}

